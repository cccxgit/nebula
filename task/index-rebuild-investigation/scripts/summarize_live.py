#!/usr/bin/env python3
"""Summarize completed live_repro.py cases without changing their evidence.

Usage from the repository root:
  python3 task/index-rebuild-investigation/scripts/summarize_live.py

Reads live/*/events.jsonl and storage-observation.log, preferring the separately
captured experiment-storage.log for experiment diagnostics. Writes summary.json
and summary.csv inside live/. No services, network calls, or third-party modules.
No input cases means no output files. Validation failures remain visible in the
summary and cause exit 1 unless --allow-incomplete was explicitly supplied.

Append diagnostics are sampled. Calculated full-round counts/bytes are labeled
source-derived and require observed replay_end counts and byte sizes to match
the fixed-width modify-only workload generated by live_repro.py.
"""

import argparse
import csv
import datetime as dt
import json
from pathlib import Path
import re
import sys


DIAGNOSTIC = re.compile(r"INDEX_DIAG\s+(\w+)\s+(.*)")
FIELDS = re.compile(r"\b([A-Za-z_]\w*)=(-?\d+)\b")
LOG_TIME = re.compile(r"^[IWEF](\d{4}(?:\d{4})?\s+\d{2}:\d{2}:\d{2}\.\d+)")
SAMPLING_NOTE = (
    "append 日志是采样：进程级 seq<=5、seq%100==0 或限速及追加总耗时>=900ms 才记录。"
    "sample_count 不能视为全部 append 次数，也不能把样本字节相加当全部写入量；"
    "source_derived 字段由已验证的 replay_end 和原源码公式推导，不是逐次实测计数。"
)


def read_events(path, errors):
    events = []
    for line_no, line in enumerate(path.read_text(errors="replace").splitlines(), 1):
        if not line.strip():
            continue
        try:
            row = json.loads(line)
            if not isinstance(row, dict):
                raise ValueError("event must be a JSON object")
            row["_source_line"] = line_no
            events.append(row)
        except (ValueError, TypeError) as exc:
            errors.append(f"events.jsonl:{line_no}: {exc}")
    return events


def only_event(events, name, errors, required=True):
    matches = [e for e in events if e.get("event") == name]
    if len(matches) != 1 and (required or matches):
        errors.append(f"Expected one {name} event, observed {len(matches)}")
    return matches[-1] if matches else None


def result_scalar(result):
    """Nebula ResultSet.as_primitive is list[dict]; tolerate a list row too."""
    if not isinstance(result, list) or not result:
        return None
    row = result[0]
    if isinstance(row, dict):
        return next(iter(row.values()), None)
    if isinstance(row, list) and row:
        return row[0]
    return None


def parse_log(content):
    records = []
    for line_no, line in enumerate(content.splitlines(), 1):
        match = DIAGNOSTIC.search(line)
        if not match:
            continue
        timestamp = LOG_TIME.match(line)
        records.append(dict(
            event=match[1], source_line=line_no,
            local_log_timestamp=timestamp[1] if timestamp else None,
            **{key: int(value) for key, value in FIELDS.findall(match[2])},
        ))
    return records


def split_diagnostics(case_dir, warnings, errors):
    all_path = case_dir / "storage-observation.log"
    exp_path = case_dir / "experiment-storage.log"
    if not all_path.exists():
        errors.append("Missing storage-observation.log")
    whole = all_path.read_text(errors="replace") if all_path.exists() else ""
    if exp_path.exists():
        experiment = exp_path.read_text(errors="replace")
        if experiment and whole.endswith(experiment):
            baseline = whole[:-len(experiment)]
        elif not experiment:
            baseline = whole
            errors.append("experiment-storage.log is empty; experiment evidence incomplete")
        else:
            baseline = ""
            warnings.append(
                "experiment-storage.log is not an exact suffix of storage-observation.log; "
                "experiment parsed independently, baseline diagnostics left unassigned"
            )
        return (baseline, experiment, "experiment-storage.log", "explicit_experiment_capture")

    # Old captures can be split only if there is exactly one baseline and one
    # experiment invocation; otherwise do not silently mix concurrent tasks.
    starts = [m.start() for m in re.finditer(r"(?m)^.*\bStart building index\s*$", whole)]
    if len(starts) == 2:
        warnings.append(
            "No experiment-storage.log; used the second 'Start building index' marker "
            "in storage-observation.log. This fallback assumes exactly two serial invocations."
        )
        return (whole[:starts[1]], whole[starts[1]:],
                "storage-observation.log", "two_serial_start_markers")
    errors.append(
        "Cannot isolate experiment diagnostics: experiment-storage.log missing and "
        f"observed {len(starts)} 'Start building index' markers (expected exactly 2)"
    )
    return ("", "", "storage-observation.log", "unresolved")


def bounds(records, field):
    values = [row[field] for row in records if field in row]
    return dict(count=len(values), minimum=min(values) if values else None,
                maximum=max(values) if values else None)


def summarize_samples(records, rate, per_operation_bytes=None):
    samples = [r for r in records if r["event"] == "append"]
    over = [r for r in samples if rate is not None and r.get("batch_bytes", -1) > rate]
    growth_pairs = []
    for before, after in zip(samples, samples[1:]):
        if not all(k in before and k in after for k in ("seq", "entries", "batch_bytes", "encoded_bytes")):
            continue
        if (before.get("space"), before.get("part")) != (after.get("space"), after.get("part")):
            continue
        seq_delta = after["seq"] - before["seq"]
        entry_delta = after["entries"] - before["entries"]
        byte_delta = after["batch_bytes"] - before["batch_bytes"]
        growth_pairs.append(dict(
            before_seq=before["seq"], after_seq=after["seq"], sequence_delta=seq_delta,
            entries_before=before["entries"], entries_after=after["entries"],
            batch_bytes_before=before["batch_bytes"], batch_bytes_after=after["batch_bytes"],
            entries_delta=entry_delta, batch_bytes_delta=byte_delta,
            encoded_bytes_delta=after["encoded_bytes"] - before["encoded_bytes"],
            consecutive_sequence=(seq_delta == 1),
            consecutive_single_operation_growth=(seq_delta == 1 and entry_delta == 2 and
                byte_delta == per_operation_bytes) if per_operation_bytes is not None else None,
        ))
    return dict(
        sampling_note=SAMPLING_NOTE,
        sample_count=len(samples),
        samples=samples,
        first_five_samples=samples[:5],
        last_five_samples=samples[-5:],
        sampled_batch_bytes=bounds(samples, "batch_bytes"),
        sampled_encoded_bytes=bounds(samples, "encoded_bytes"),
        sampled_limit_ms=bounds(samples, "limit_ms"),
        sampled_append_ms=bounds(samples, "append_ms"),
        over_rate_sample_count=len(over),
        over_rate_limit_ms=bounds(over, "limit_ms"),
        over_rate_append_ms=bounds(over, "append_ms"),
        over_rate_limit_at_least_900ms_samples=sum(r.get("limit_ms", -1) >= 900 for r in over),
        consecutive_single_operation_growth_pairs=sum(
            p["consecutive_single_operation_growth"] is True for p in growth_pairs),
        adjacent_sample_growth=growth_pairs,
    )


def source_round_formula(n, key_bytes, batch, rate):
    """Exact sums for one completed, fixed-width, modify-only snapshot round."""
    d = 2 * key_bytes + 16
    first_flush = batch // d + 1
    if n >= first_flush:
        calls = n - first_flush + 2
        row_copies = (n * (n + 1) - (first_flush - 1) * first_flush) // 2 + n
    else:
        calls, row_copies = 1, n  # Includes the real unconditional empty append for N=0.
    first_large_flush = max(first_flush, rate // d + 1)
    forced_sleeps = max(0, n - first_large_flush + 1) + int(n * d > rate)
    return dict(
        observed_operation_records=n,
        index_key_bytes=key_bytes,
        operation_payload_bytes=d,
        first_flush_record=first_flush,
        first_over_rate_flushed_record=first_large_flush,
        append_calls=calls,
        logical_record_copies=row_copies,
        lowlevel_batch_entries=2 * row_copies,
        payload_bytes=d * row_copies,
        encoded_bytes=(d + 18) * row_copies + 13 * calls,
        forced_one_second_sleep_calls=forced_sleeps,
        forced_sleep_seconds_lower_bound=forced_sleeps,
    )


def replay_summary(records, errors, phase):
    begins = [r for r in records if r["event"] == "replay_begin"]
    ends = [r for r in records if r["event"] == "replay_end"]
    identities = {(r.get("space"), r.get("part")) for r in records}
    if len(identities) > 1:
        errors.append(f"{phase}: multiple space/part pairs present: {sorted(identities, key=str)}")
    begun = [(r.get("space"), r.get("part"), r.get("round")) for r in begins]
    ended = [(r.get("space"), r.get("part"), r.get("round")) for r in ends]
    if begun != ended:
        errors.append(f"{phase}: replay_begin/replay_end mismatch; an unfinished round may remain")
    if len(ended) != len(set(ended)):
        errors.append(f"{phase}: duplicate replay_end round identities")
    return dict(
        begin_records=begins, end_records=ends,
        operations_by_round=[r.get("operations") for r in ends],
        locked_wait_records=[r for r in records if r["event"].startswith("locked_wait")],
        identity_pairs=[list(pair) for pair in sorted(identities, key=str)],
    )


def job_summary(events, submit_name, explicit_id, errors):
    submit = only_event(events, submit_name, errors)
    raw_id = result_scalar(submit.get("result")) if submit else None
    try:
        parsed_id = int(raw_id) if raw_id is not None else None
    except (TypeError, ValueError):
        parsed_id = None
        errors.append(f"{submit_name}: cannot parse job ID from first result cell")
    if explicit_id is not None and parsed_id is not None and explicit_id != parsed_id:
        errors.append(f"{submit_name}: success event job ID {explicit_id} differs from submit {parsed_id}")
    job_id = explicit_id if explicit_id is not None else parsed_id
    terminals = [e for e in events if e.get("event") == "job_terminal" and e.get("job") == job_id]
    terminal = terminals[-1] if terminals else None
    if len(terminals) != 1:
        errors.append(f"{submit_name}: expected one terminal event for job {job_id}, got {len(terminals)}")
    if terminal and terminal.get("status") != "FINISHED":
        errors.append(f"{submit_name}: terminal status is {terminal.get('status')}")
    return dict(
        job_id=job_id,
        status=terminal.get("status") if terminal else None,
        job_seconds=terminal.get("job_seconds") if terminal else None,
        submit_rpc_seconds=submit.get("seconds") if submit else None,
        submit_event_utc=submit.get("utc") if submit else None,
        terminal_event_utc=terminal.get("utc") if terminal else None,
        timing_note="job_seconds 为 live_repro.py 从提交前至 SHOW JOB 发现结束的墙钟耗时，包含最多约2秒轮询延迟。",
    )


def effective_flags(events, errors):
    gets = [e for e in events if e.get("event") == "flags_get"]
    values = {}
    for event in gets:
        try:
            response = event.get("response")
            response = json.loads(response) if isinstance(response, str) else response
            values = {item["name"]: item["value"] for item in response["flags"]}
        except (ValueError, TypeError, KeyError) as exc:
            errors.append(f"flags_get line {event.get('_source_line')}: {exc}")
    return values


def summarize_case(path):
    errors, warnings = [], []
    events = read_events(path, errors)
    parameter_event = only_event(events, "parameters", errors)
    params = parameter_event.get("parameters", {}) if parameter_event else {}
    kind = params.get("kind")
    batch, rate, expected_n = (params.get(k) for k in ("batch", "rate", "backlog"))
    if kind not in ("TAG", "EDGE"):
        errors.append(f"Unsupported or missing kind {kind!r}")
    key_bytes = {"TAG": 16 * 256 + 16, "EDGE": 16 * 256 + 32}.get(kind)
    for name, value in (("batch", batch), ("rate", rate), ("backlog", expected_n)):
        if not isinstance(value, int) or value <= 0:
            errors.append(f"Invalid or missing parameter {name}={value!r}")
    params_valid = key_bytes is not None and all(isinstance(v, int) and v > 0
                                                for v in (batch, rate, expected_n))
    d = 2 * key_bytes + 16 if key_bytes is not None else None
    flags = effective_flags(events, errors)
    flags_match = True
    for field, expected in (("rebuild_index_batch_size", batch), ("rebuild_index_part_rate_limit", rate)):
        try:
            if int(flags[field]) != expected:
                raise ValueError(f"observed {flags[field]}, requested {expected}")
        except (ValueError, KeyError, TypeError) as exc:
            flags_match = False
            errors.append(f"Effective {field} not verified: {exc}")

    success = only_event(events, "success", errors)
    baseline_job = job_summary(events, "baseline_submit",
                               success.get("baseline_job") if success else None, errors)
    experiment_job = job_summary(events, "experiment_submit",
                                 success.get("experiment_job") if success else None, errors)
    evidence = only_event(events, "reproduction_evidence", errors)
    verify = only_event(events, "verify_concurrent_index_rows", errors)
    verified_rows = result_scalar(verify.get("result")) if verify else None
    if verified_rows != expected_n:
        errors.append(f"LOOKUP row count {verified_rows!r} differs from requested backlog {expected_n!r}")
    failed_queries = [e for e in events if e.get("ok") is False]
    if failed_queries:
        errors.append(f"{len(failed_queries)} recorded query failures")

    baseline_text, experiment_text, experiment_source, isolation = split_diagnostics(
        path.parent, warnings, errors)
    baseline_records, experiment_records = parse_log(baseline_text), parse_log(experiment_text)
    baseline_rounds = replay_summary(baseline_records, errors, "baseline")
    experiment_rounds = replay_summary(experiment_records, errors, "experiment")
    samples = summarize_samples(experiment_records, rate if isinstance(rate, int) else None, d)

    ends = experiment_rounds["end_records"]
    count_valid = bool(ends) and all(isinstance(r.get("operations"), int) and r["operations"] >= 0 for r in ends)
    observed_total = sum(r["operations"] for r in ends) if count_valid else None
    observed_max = max((r["operations"] for r in ends), default=None) if count_valid else None
    count_matches = count_valid and observed_total == expected_n and observed_max == expected_n
    if not count_matches:
        errors.append(
            f"replay_end backlog assertion failed: sum={observed_total}, max={observed_max}, "
            f"requested N={expected_n}; expected exactly one complete nonempty round"
        )
    if evidence and evidence.get("replay_operations_by_round") != experiment_rounds["operations_by_round"]:
        errors.append("reproduction_evidence rounds differ from experiment replay_end records")
    byte_matches = params_valid and count_valid
    if byte_matches:
        for row in ends:
            n = row["operations"]
            if row.get("retained_bytes") != n * d or row.get("retained_entries") != 2 * n:
                byte_matches = False
                errors.append(f"round {row.get('round')}: retained bytes/entries do not match fixed-width modify-only N")
    sample_sizes_match = True
    for sample in samples["samples"]:
        if not all(k in sample for k in ("entries", "batch_bytes", "encoded_bytes")):
            sample_sizes_match = False
            errors.append(f"append seq={sample.get('seq')}: required size fields missing")
        elif sample["encoded_bytes"] != sample["batch_bytes"] + 9 * sample["entries"] + 13:
            sample_sizes_match = False
            errors.append(f"append seq={sample.get('seq')}: encoded length does not match source encoder")
        if sample.get("rc") != 0:
            errors.append(f"append seq={sample.get('seq')}: rc={sample.get('rc')} is not success")

    derivation_valid = (params_valid and flags_match and count_matches and byte_matches
                        and sample_sizes_match and experiment_job["status"] == "FINISHED"
                        and not errors)
    derived_rounds = []
    if derivation_valid:
        for row in ends:
            derived_rounds.append(dict(
                space=row.get("space"), part=row.get("part"), round=row.get("round"),
                **source_round_formula(row["operations"], key_bytes, batch, rate)))
    fields = ("append_calls", "logical_record_copies", "lowlevel_batch_entries", "payload_bytes",
              "encoded_bytes", "forced_one_second_sleep_calls", "forced_sleep_seconds_lower_bound")
    data_rounds = [r for r in derived_rounds if r["observed_operation_records"] > 0]
    def total(rows):
        return {field: sum(row[field] for row in rows) for field in fields} if derivation_valid else None

    baseline_seconds, experiment_seconds = baseline_job["job_seconds"], experiment_job["job_seconds"]
    return dict(
        case=path.parent.name,
        case_directory=str(path.parent.resolve()),
        parameters=params,
        effective_flags=flags,
        baseline_job=baseline_job,
        experiment_job=experiment_job,
        experiment_minus_baseline_seconds=round(experiment_seconds-baseline_seconds, 3)
            if isinstance(experiment_seconds, (int, float)) and isinstance(baseline_seconds, (int, float)) else None,
        baseline_replay=baseline_rounds,
        experiment_replay=experiment_rounds,
        experiment_diagnostic_source=experiment_source,
        experiment_isolation_method=isolation,
        experiment_append_samples=samples,
        observed_lookup_concurrent_rows=verified_rows,
        recorded_reproduction_evidence={k: v for k, v in evidence.items() if not k.startswith("_")}
            if evidence else None,
        source_derived=dict(
            valid=derivation_valid,
            source="Original RebuildIndexTask.cpp loop + BatchHolder + encodeBatchValue + RateLimiter; base de9b3ed800a6627d9845e9289b6bbc5b6faf460a",
            assumptions="单分区、16列string(256) NOT NULL、VID INT64、无TTL、新增唯一点/正向边、单索引、modify-only；K(TAG)=4112,K(EDGE)=4128,d=2K+16。",
            note="数学推导的完整轮计数；所有N来自完成的replay_end，并与请求backlog及retained_bytes/entries断言一致。编码量是累计编码字符串长度，不是磁盘大小或网络实测流量。",
            index_key_bytes=key_bytes,
            operation_payload_bytes=d,
            backlog_assertion=dict(requested=expected_n, replay_end_sum=observed_total,
                                   replay_end_max=observed_max, passed=count_matches),
            retained_size_assertion_passed=bool(byte_matches),
            rounds=derived_rounds,
            nonempty_round_totals=total(data_rounds),
            all_completed_round_totals=total(derived_rounds),
        ),
        validation_passed=not errors,
        errors=errors,
        warnings=warnings,
    )


def csv_row(case):
    params = case["parameters"]
    sample = case["experiment_append_samples"]
    derivation = case["source_derived"]
    totals = derivation["nonempty_round_totals"] or {}
    row = dict(
        case=case["case"], kind=params.get("kind"), space_name=params.get("name"),
        seed=params.get("seed"), requested_backlog=params.get("backlog"),
        batch_bytes=params.get("batch"), rate_bytes_per_sec=params.get("rate"),
        index_key_bytes=derivation["index_key_bytes"], operation_payload_bytes=derivation["operation_payload_bytes"],
        baseline_job=case["baseline_job"]["job_id"], baseline_status=case["baseline_job"]["status"],
        baseline_seconds=case["baseline_job"]["job_seconds"],
        experiment_job=case["experiment_job"]["job_id"], experiment_status=case["experiment_job"]["status"],
        experiment_seconds=case["experiment_job"]["job_seconds"],
        experiment_minus_baseline_seconds=case["experiment_minus_baseline_seconds"],
        replay_operations_by_round=json.dumps(case["experiment_replay"]["operations_by_round"]),
        sampled_append_calls=sample["sample_count"],
        consecutive_single_operation_growth_pairs=sample["consecutive_single_operation_growth_pairs"],
        sampled_over_rate_calls=sample["over_rate_sample_count"],
        sampled_over_rate_limit_ms_min=sample["over_rate_limit_ms"]["minimum"],
        sampled_over_rate_limit_ms_max=sample["over_rate_limit_ms"]["maximum"],
        sampled_over_rate_append_ms_min=sample["over_rate_append_ms"]["minimum"],
        sampled_over_rate_append_ms_max=sample["over_rate_append_ms"]["maximum"],
        sampled_max_batch_bytes=sample["sampled_batch_bytes"]["maximum"],
        source_derived_valid=derivation["valid"],
        source_derived_nonempty_append_calls=totals.get("append_calls"),
        source_derived_nonempty_encoded_bytes=totals.get("encoded_bytes"),
        source_derived_nonempty_forced_sleep_calls=totals.get("forced_one_second_sleep_calls"),
        observed_lookup_concurrent_rows=case["observed_lookup_concurrent_rows"],
        validation_passed=case["validation_passed"],
        errors=" | ".join(case["errors"]), warnings=" | ".join(case["warnings"]),
        sampling_note=SAMPLING_NOTE,
    )
    return row


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--live-dir", type=Path, default=Path(__file__).resolve().parents[1] / "live")
    parser.add_argument("--allow-incomplete", action="store_true",
                        help="Still record validation failures, but return success for partial captures")
    args = parser.parse_args()
    paths = sorted(args.live_dir.glob("*/events.jsonl"))
    if not paths:
        print(f"No case events.jsonl files found in {args.live_dir}; no summary files written.", file=sys.stderr)
        return 2
    cases = [summarize_case(path) for path in paths]
    document = dict(
        schema_version=1,
        generated_utc=dt.datetime.now(dt.timezone.utc).isoformat(),
        input_case_count=len(cases),
        all_cases_valid=all(case["validation_passed"] for case in cases),
        sampling_note=SAMPLING_NOTE,
        cases=cases,
    )
    json_path, csv_path = args.live_dir / "summary.json", args.live_dir / "summary.csv"
    json_path.write_text(json.dumps(document, ensure_ascii=False, indent=2) + "\n")
    rows = [csv_row(case) for case in cases]
    with csv_path.open("w", newline="", encoding="utf-8") as out:
        writer = csv.DictWriter(out, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    print(f"Wrote {json_path} and {csv_path}; cases={len(cases)}, all_valid={document['all_cases_valid']}")
    for case in cases:
        print(f"{case['case']}: baseline={case['baseline_job']['job_seconds']}s, "
              f"experiment={case['experiment_job']['job_seconds']}s, "
              f"rounds={case['experiment_replay']['operations_by_round']}, "
              f"sampled_appends={case['experiment_append_samples']['sample_count']}, "
              f"valid={case['validation_passed']}")
        for error in case["errors"]:
            print(f"  ERROR: {error}", file=sys.stderr)
    return 0 if document["all_cases_valid"] or args.allow_incomplete else 1


if __name__ == "__main__":
    raise SystemExit(main())
