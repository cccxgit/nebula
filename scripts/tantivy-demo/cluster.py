#!/usr/bin/env python3
"""Operate only the isolated, local Tantivy competition cluster."""

import argparse
import datetime
import json
import os
from pathlib import Path
import resource
import signal
import socket
import subprocess
import sys
import time


REPO = Path(__file__).resolve().parents[2]
SERVICES = (
    ("metad", "nebula-metad", 9559, 19559),
    ("storage1", "nebula-storaged", 9779, 19779),
    ("storage2", "nebula-storaged", 9789, 19789),
    ("storage3", "nebula-storaged", 9799, 19799),
    ("graphd", "nebula-graphd", 9669, 19669),
)


def record(event, **fields):
    entry = {"time": datetime.datetime.now(datetime.timezone.utc).isoformat(),
             "event": event, **fields}
    path = REPO / "task-logs/tantivy-demo/cluster.jsonl"
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("a") as output:
        output.write(json.dumps(entry, ensure_ascii=False) + "\n")
    print(json.dumps(entry, ensure_ascii=False), flush=True)


def listening(port):
    with socket.socket() as sock:
        sock.settimeout(0.25)
        return sock.connect_ex(("127.0.0.1", port)) == 0


def paths(runtime, service):
    name, binary, _, _ = service
    directory = runtime / "tantivy-demo" / name
    return (runtime / "bin" / binary, directory,
            directory / "pids" / (binary + ".pid"), directory / "service.conf")


def owned_pid(runtime, service):
    binary, _, pid_file, config = paths(runtime, service)
    try:
        pid = int(pid_file.read_text().strip())
    except (FileNotFoundError, ValueError):
        return None
    try:
        command = Path(f"/proc/{pid}/cmdline").read_bytes().split(b"\0")
        executable = os.readlink(f"/proc/{pid}/exe").removesuffix(" (deleted)")
    except (FileNotFoundError, ProcessLookupError):
        return None
    if executable != str(binary.resolve()) or str(config).encode() not in b" ".join(command):
        raise RuntimeError(f"PID {pid} from {pid_file} belongs to another process; refusing to act")
    return pid


def pidfile_revision(pid_file):
    """Recognize a newly published PID even if its process already crashed."""
    try:
        pid = int(pid_file.read_text().strip())
        stat = pid_file.stat()
        return stat.st_ino, stat.st_mtime_ns, pid
    except (FileNotFoundError, ValueError):
        return None


def initialize(runtime):
    for service in SERVICES:
        name, binary_name, port, http = service
        _, directory, pid_file, config = paths(runtime, service)
        if owned_pid(runtime, service):
            raise RuntimeError(f"Stop this demo cluster before rewriting {config}")
        for child in ("data", "logs", "pids"):
            (directory / child).mkdir(parents=True, exist_ok=True)
        template = REPO / "conf" / (binary_name + ".conf.default")
        settings = {}
        for raw in template.read_text().splitlines():
            if raw.startswith("--") and "=" in raw:
                key, value = raw[2:].split("=", 1)
                settings[key] = value
        settings.update(daemonize="true", pid_file=str(pid_file),
                        log_dir=str(directory / "logs"), local_ip="127.0.0.1",
                        ws_ip="127.0.0.1", port=str(port), ws_http_port=str(http),
                        meta_server_addrs="127.0.0.1:9559")
        if name == "graphd":
            settings.update(num_netio_threads="2", num_worker_threads="4",
                            accept_partial_success="false", enable_udf="false")
        else:
            settings.update(data_path=str(directory / "data"), heartbeat_interval_secs="1")
        if name.startswith("storage"):
            settings.update(num_io_threads="2", num_worker_threads="4",
                            raft_heartbeat_interval_secs="5", rocksdb_block_cache="64",
                            rocksdb_compression="lz4", wal_ttl="3600")
        config.write_text("# Isolated local competition cluster; generated by cluster.py\n" +
                          "".join(f"--{key}={value}\n" for key, value in settings.items()))
    record("initialized", runtime=str(runtime), storaged_processes=3,
           partition_count=20, replica_factor=3)


def start(runtime, timeout):
    soft, hard = resource.getrlimit(resource.RLIMIT_NOFILE)
    if hard != resource.RLIM_INFINITY and hard < 65536:
        raise RuntimeError(f"Open-file hard limit is {hard}; raise it to at least 65536")
    resource.setrlimit(resource.RLIMIT_NOFILE, (max(soft, 65536), hard))
    # Check the entire port set before starting any process; never interrupt other clusters.
    for service in SERVICES:
        name, _, port, http = service
        binary, _, _, config = paths(runtime, service)
        if not binary.is_file() or not config.is_file():
            raise RuntimeError(f"Missing {binary} or {config}; install binaries and run init first")
        if owned_pid(runtime, service):
            continue
        ports = [port, http]
        if name.startswith("storage"):
            ports += [port - 2, port - 1, port + 1]
        elif name == "metad":
            ports += [port + 1]
        conflicts = [candidate for candidate in ports if listening(candidate)]
        if conflicts:
            raise RuntimeError(f"Ports {conflicts} are in use; no other service will be stopped")
    # A fresh storaged may wait for host registration before opening its RPC port.
    # Start the metadata/query control plane first, then register hosts before storaged.
    by_name = {service[0]: service for service in SERVICES}
    start_service(runtime, by_name["metad"], timeout)
    start_service(runtime, by_name["graphd"], timeout)
    register_hosts(timeout, runtime=runtime)
    for name in ("storage1", "storage2", "storage3"):
        start_service(runtime, by_name[name], timeout)


def start_service(runtime, service, timeout):
    name, _, port, _ = service
    binary, directory, pid_file, config = paths(runtime, service)
    pid = owned_pid(runtime, service)
    if pid is not None and listening(port):
        record("already_running", service=name, pid=pid)
        return
    old_revision = pidfile_revision(pid_file)
    if pid is None:
        with (directory / "logs/launcher.log").open("a") as output:
            try:
                subprocess.run([str(binary), "--flagfile=" + str(config)], cwd=runtime,
                               stdout=output, stderr=subprocess.STDOUT, check=True, timeout=30)
            except subprocess.SubprocessError as error:
                raise RuntimeError(f"{name} launcher failed: {error}; inspect {directory / 'logs'}") from error
    else:
        record("waiting_for_existing_process", service=name, pid=pid)
    deadline = time.monotonic() + timeout
    pid_deadline = time.monotonic() + min(timeout, 5)
    observed_pid = pid
    while time.monotonic() < deadline:
        pid = owned_pid(runtime, service)
        if pid is not None and listening(port):
            record("started", service=name, pid=pid, port=port,
                   open_files_limit=resource.getrlimit(resource.RLIMIT_NOFILE)[0])
            return
        if pid is not None:
            observed_pid = pid
        else:
            revision = pidfile_revision(pid_file)
            if observed_pid is not None or (revision is not None and revision != old_revision):
                dead_pid = observed_pid if observed_pid is not None else revision[2]
                record("startup_process_exited", service=name, pid=dead_pid,
                       logs=str(directory / "logs"))
                raise RuntimeError(f"{name} PID {dead_pid} exited before listening on {port}; "
                                   f"inspect {directory / 'logs'}")
            if time.monotonic() >= pid_deadline:
                raise RuntimeError(f"{name} did not publish a live PID within 5 seconds; "
                                   f"inspect {directory / 'logs'}")
        time.sleep(0.25)
    raise RuntimeError(f"{name} did not listen on {port}; inspect {directory / 'logs'}")


def register_hosts(timeout, runtime=None):
    try:
        from nebula3.Config import Config
        from nebula3.gclient.net import ConnectionPool
    except ImportError as error:
        raise RuntimeError("Host registration requires nebula3-python; install the benchmark requirements") from error
    expected = {("127.0.0.1", service[2]) for service in SERVICES
                if service[0].startswith("storage")}
    deadline = time.monotonic() + timeout
    last_error = None
    while time.monotonic() < deadline:
        if runtime is not None:
            for service in SERVICES:
                if service[0] in ("metad", "graphd") and owned_pid(runtime, service) is None:
                    directory = paths(runtime, service)[1]
                    raise RuntimeError(f"{service[0]} exited during host registration; "
                                       f"inspect {directory / 'logs'}")
        pool = ConnectionPool()
        session = None
        try:
            config = Config()
            config.max_connection_pool_size = 2
            config.timeout = 5000
            if not pool.init([("127.0.0.1", 9669)], config):
                raise RuntimeError("graphd connection is not ready")
            session = pool.get_session("root", os.environ.get("NEBULA_PASSWORD", "nebula"))
            result = session.execute("SHOW HOSTS")
            if not result.is_succeeded():
                raise RuntimeError(str(result.error_msg()))
            present = set()
            for host, port in zip(result.column_values("Host"), result.column_values("Port")):
                if host.is_string() and port.is_int():
                    present.add((host.as_string(), port.as_int()))
            missing = sorted(expected - present)
            if missing:
                statement = "ADD HOSTS " + ",".join(f'"{host}":{port}' for host, port in missing)
                result = session.execute(statement)
                if not result.is_succeeded():
                    raise RuntimeError(str(result.error_msg()))
            record("hosts_registered", hosts=sorted(expected), newly_registered=missing)
            return
        except Exception as error:
            last_error = str(error)
        finally:
            if session is not None:
                session.release()
            pool.close()
        time.sleep(1)
    raise RuntimeError(f"Could not register storage hosts before starting storaged: {last_error}")


def stop(runtime, timeout):
    # Stop only verified PIDs from these exact flagfiles. Never use pkill or killall.
    for service in reversed(SERVICES):
        pid = owned_pid(runtime, service)
        if pid is None:
            record("already_stopped", service=service[0])
            continue
        os.kill(pid, signal.SIGTERM)
        deadline = time.monotonic() + timeout
        while time.monotonic() < deadline:
            if owned_pid(runtime, service) is None:
                record("stopped", service=service[0], pid=pid)
                break
            time.sleep(0.25)
        else:
            raise RuntimeError(f"{service[0]} PID {pid} did not exit; leaving it for inspection")


def status(runtime):
    healthy = True
    for service in SERVICES:
        pid = owned_pid(runtime, service)
        up = pid is not None and listening(service[2])
        record("status", service=service[0], running=up, pid=pid, port=service[2],
               http_port=service[3])
        healthy = healthy and up
    return 0 if healthy else 1


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("action", choices=("init", "start", "stop", "status"))
    parser.add_argument("--runtime", type=Path, default=Path("/home/sch/nebula-run/3.6-tantivy"))
    parser.add_argument("--timeout", type=float, default=60)
    args = parser.parse_args()
    runtime = args.runtime.resolve()
    try:
        if args.action == "init":
            initialize(runtime)
        elif args.action == "start":
            start(runtime, args.timeout)
        elif args.action == "stop":
            stop(runtime, args.timeout)
        else:
            return status(runtime)
    except Exception as error:
        record("error", action=args.action, error=str(error))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
